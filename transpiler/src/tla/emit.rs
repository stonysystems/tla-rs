//! Emitter (Phase 52.M1.c): a projected module becomes Verus source.
//!
//! [`crate::tla::projection`] and [`crate::tla::action_projection`] decide
//! *what* the single-process spec is; this module writes it out in the shape
//! the corpus goldens fix.
//!
//! The emitter refuses to write an incomplete spec. If any part of the
//! projection reported a gap, [`emit`] returns them instead of source: a file
//! that is missing a conjunct still looks like a spec, and would be verified,
//! reviewed and trusted as one.

use std::fmt::Write as _;

use crate::tla::action_projection::{ActionKind, ProjectedModule};

/// Emit the projected module as Verus source, or the gaps that prevent it.
pub fn emit(projected: &ProjectedModule) -> Result<String, Vec<String>> {
    let gaps = collect_gaps(projected);
    if !gaps.is_empty() {
        return Err(gaps);
    }

    let mut out = String::new();
    let _ = writeln!(
        out,
        "//! Single-process Verus spec projected from TLA+ module `{}`.\n\
         //!\n\
         //! Generated by `verus-transpile clean-tla`. Do not edit by hand: the\n\
         //! clean-subset spec it came from is the source of truth.\n",
        projected.spec.module_name
    );
    out.push_str("use vstd::prelude::*;\n\nverus! {\n");

    emit_enums(&mut out, projected);
    emit_records(&mut out, projected);
    emit_messages(&mut out, projected);
    emit_state(&mut out, projected);
    emit_constants(&mut out, projected);
    emit_helpers(&mut out, projected);
    emit_init(&mut out, projected);
    emit_actions(&mut out, projected);
    emit_dispatch(&mut out, projected);
    emit_next(&mut out, projected);

    out.push_str("}\n");
    Ok(out)
}

fn collect_gaps(projected: &ProjectedModule) -> Vec<String> {
    let mut gaps = projected.spec.gaps.clone();
    gaps.extend(projected.init_gaps.iter().cloned());
    for helper in &projected.helpers {
        gaps.extend(
            helper
                .gaps
                .iter()
                .map(|g| format!("helper `{}`: {g}", helper.source_name)),
        );
    }
    for action in &projected.actions {
        gaps.extend(
            action
                .gaps
                .iter()
                .map(|g| format!("action `{}`: {g}", action.source_name)),
        );
    }
    gaps
}

fn emit_enums(out: &mut String, projected: &ProjectedModule) {
    for (name, variants) in &projected.spec.enums {
        let _ = writeln!(out, "    pub enum {name} {{");
        for variant in variants {
            let _ = writeln!(out, "        {variant},");
        }
        out.push_str("    }\n\n");
    }
}

fn emit_records(out: &mut String, projected: &ProjectedModule) {
    for (name, fields) in &projected.spec.records {
        let _ = writeln!(out, "    pub struct {name} {{");
        for (field, ty) in fields {
            let _ = writeln!(out, "        pub {field}: {},", ty.render());
        }
        out.push_str("    }\n\n");
    }
}

fn emit_messages(out: &mut String, projected: &ProjectedModule) {
    if projected.spec.messages.is_empty() {
        return;
    }
    out.push_str("    /// Wire messages. Routing lives on the packet, not in the payload.\n");
    out.push_str("    pub enum LMessage {\n");
    for variant in &projected.spec.messages {
        if variant.fields.is_empty() {
            let _ = writeln!(out, "        {},", variant.name);
        } else {
            let fields = variant
                .fields
                .iter()
                .map(|(name, ty)| format!("{name}: {}", ty.render()))
                .collect::<Vec<_>>()
                .join(", ");
            let _ = writeln!(out, "        {} {{ {fields} }},", variant.name);
        }
    }
    out.push_str("    }\n\n");
    out.push_str("    /// A message addressed to a peer.\n");
    out.push_str(
        "    pub struct LPacket {\n        pub dst: int,\n        pub msg: LMessage,\n    }\n\n",
    );
}

fn emit_state(out: &mut String, projected: &ProjectedModule) {
    out.push_str("    /// This node's state.\n    pub struct LState {\n");
    for field in &projected.spec.state_fields {
        let _ = writeln!(out, "        pub {}: {},", field.name, field.ty.render());
    }
    out.push_str("    }\n\n");
}

fn emit_constants(out: &mut String, projected: &ProjectedModule) {
    out.push_str("    /// Protocol constants, including this node's own identity.\n");
    out.push_str("    pub struct LConstants {\n");
    for (name, ty) in &projected.spec.constants {
        let _ = writeln!(out, "        pub {name}: {},", ty.render());
    }
    out.push_str("    }\n\n");
}

fn emit_helpers(out: &mut String, projected: &ProjectedModule) {
    for helper in &projected.helpers {
        let mut params = Vec::new();
        if helper.reads_state {
            params.push("s: LState".to_string());
        }
        params.push("c: LConstants".to_string());
        params.extend(helper.params.iter().cloned());
        let _ = writeln!(
            out,
            "    pub open spec fn {}({}) -> {} {{",
            helper.name,
            params.join(", "),
            helper
                .return_type
                .as_deref()
                .unwrap_or_else(|| helper_return_type(helper))
        );
        let _ = writeln!(out, "        {}", helper.body);
        out.push_str("    }\n\n");
    }
}

/// A helper is a predicate unless its body is plainly a value.
fn helper_return_type(helper: &crate::tla::action_projection::ProjectedHelper) -> &'static str {
    let body = helper.body.trim();
    if body.starts_with("Map::new(") || body.contains(".insert(") {
        "Map<int, int>"
    } else if body.starts_with("Set::") {
        "Set<int>"
    } else if body.contains("==")
        || body.contains("&&")
        || body.contains("||")
        || body.contains('<')
        || body.contains('>')
    {
        "bool"
    } else {
        "int"
    }
}

fn emit_init(out: &mut String, projected: &ProjectedModule) {
    out.push_str("    pub open spec fn LInit(s: LState, c: LConstants) -> bool {\n");
    for conjunct in &projected.init {
        let _ = writeln!(out, "        &&& {conjunct}");
    }
    out.push_str("    }\n\n");
}

fn emit_actions(out: &mut String, projected: &ProjectedModule) {
    for action in &projected.actions {
        let mut params = vec![
            "s: LState".to_string(),
            "s_: LState".to_string(),
            "c: LConstants".to_string(),
        ];
        params.extend(action.params.iter().cloned());
        params.push("sent_packets: Set<LPacket>".to_string());
        let _ = writeln!(
            out,
            "    pub open spec fn {}(\n        {},\n    ) -> bool {{",
            action.name,
            params.join(",\n        ")
        );
        for conjunct in action.conjuncts.iter().chain(action.frame.iter()) {
            let _ = writeln!(out, "        &&& {conjunct}");
        }
        out.push_str("    }\n\n");
    }
}

fn emit_dispatch(out: &mut String, projected: &ProjectedModule) {
    let receives: Vec<_> = projected
        .actions
        .iter()
        .filter(|a| a.kind == ActionKind::Receive)
        .collect();
    if receives.is_empty() {
        return;
    }

    out.push_str(
        "    /// Dispatch on the received message. Delivery and the tag are the\n\
         \x20   /// framework's; each handler states only its own conditions.\n",
    );
    out.push_str(
        "    pub open spec fn LHandleMessage(\n        s: LState,\n        s_: LState,\n\
         \x20       c: LConstants,\n        src: int,\n        msg: LMessage,\n\
         \x20       sent_packets: Set<LPacket>,\n    ) -> bool {\n        match msg {\n",
    );
    for action in &receives {
        let Some(tag) = &action.handles_tag else {
            continue;
        };
        let Some(variant) = projected.spec.messages.iter().find(|m| m.tag == *tag) else {
            continue;
        };
        let binding = if variant.fields.is_empty() {
            String::new()
        } else {
            format!(
                " {{ {} }}",
                variant
                    .fields
                    .iter()
                    .map(|(name, _)| name.clone())
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        };
        let args: Vec<String> = action
            .params
            .iter()
            .map(|p| p.split(':').next().unwrap_or(p).trim().to_string())
            .collect();
        // A handler may take nothing beyond the state -- a `Commit` message
        // carries no payload and this one does not use the sender -- so the
        // argument list has to close up rather than leave an empty slot.
        let mut call_args = vec!["s".to_string(), "s_".to_string(), "c".to_string()];
        call_args.extend(args);
        call_args.push("sent_packets".to_string());
        let _ = writeln!(
            out,
            "            LMessage::{}{binding} =>\n                {}({}),",
            variant.name,
            action.name,
            call_args.join(", ")
        );
    }
    // A message kind no action handles cannot be acted on. Saying so is not the
    // same as omitting it: without this arm the match is non-exhaustive, and
    // with a silent `true` the node could take an arbitrary step on receipt.
    let handled: Vec<&str> = receives
        .iter()
        .filter_map(|a| a.handles_tag.as_deref())
        .collect();
    if projected
        .spec
        .messages
        .iter()
        .any(|m| !handled.contains(&m.tag.as_str()))
    {
        out.push_str("            _ => false,\n");
    }

    out.push_str("        }\n    }\n\n");
}

fn emit_next(out: &mut String, projected: &ProjectedModule) {
    out.push_str(
        "    pub open spec fn LNext(\n        s: LState,\n        s_: LState,\n\
         \x20       c: LConstants,\n        sent_packets: Set<LPacket>,\n    ) -> bool {\n",
    );
    for action in projected
        .actions
        .iter()
        .filter(|a| a.kind == ActionKind::Local)
    {
        // Verus's `|||` reads as a leading disjunct on every line, including
        // the first, so no special case is needed.
        //
        // A local action's own parameters are existentially quantified, as they
        // are in the source: `\E b \in Ballot : Phase1a(a, b)`.
        if action.params.is_empty() {
            let _ = writeln!(out, "        ||| {}(s, s_, c, sent_packets)", action.name);
        } else {
            let names: Vec<String> = action
                .params
                .iter()
                .map(|p| p.split(':').next().unwrap_or(p).trim().to_string())
                .collect();
            // The binder's set travels with the parameter: `\E b \in Ballot`
            // is a condition on `b`, and without it `LNext` would admit
            // parameters the source spec has no state for.
            let bounds: Vec<String> = action.param_bounds.iter().flatten().cloned().collect();
            let guard = if bounds.is_empty() {
                String::new()
            } else {
                format!("{} && ", bounds.join(" && "))
            };
            let _ = writeln!(
                out,
                "        ||| (exists|{}|\n                {guard}{}(s, s_, c, {}, sent_packets))",
                action.params.join(", "),
                action.name,
                names.join(", ")
            );
        }
    }
    if projected
        .actions
        .iter()
        .any(|a| a.kind == ActionKind::Receive)
    {
        out.push_str(
            "        ||| (exists|src: int, msg: LMessage|\n\
             \x20               LHandleMessage(s, s_, c, src, msg, sent_packets))\n",
        );
    }
    out.push_str("    }\n");
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::tla::action_projection::project;
    use crate::tla::parse_module;

    const SPEC: &str = r#"---- MODULE Test ----
VARIABLES x, pc, network
Message == [type: {"ping"}, src: Proc, dst: Proc, val: Nat]
Ping(s, d, v) == [type |-> "ping", src |-> s, dst |-> d, val |-> v]
TypeOK == /\ x \in [Proc -> Nat]
          /\ pc \in [Proc -> {"idle", "done"}]
Init == /\ x = [p \in Proc |-> 0]
        /\ pc = [p \in Proc |-> "idle"]
        /\ network = {}
Send(p) == /\ pc[p] = "idle"
           /\ network' = network \cup {Ping(p, 1, x[p])}
           /\ pc' = [pc EXCEPT ![p] = "done"]
           /\ x' = x
Recv(p, m) == /\ m.dst = p
              /\ m.type = "ping"
              /\ x' = [x EXCEPT ![p] = m.val]
              /\ network' = network \ {m}
              /\ pc' = pc
Next == \E p \in Proc : Send(p) \/ \E m \in network : Recv(p, m)
===="#;

    fn emitted() -> String {
        let module = parse_module(SPEC).expect("spec must parse");
        let projected = project(&module).expect("spec must be clean");
        emit(&projected).unwrap_or_else(|gaps| panic!("emission blocked by gaps: {gaps:?}"))
    }

    #[test]
    fn emits_the_declarations() {
        let out = emitted();
        assert!(out.contains("pub enum LPc {"), "{out}");
        assert!(out.contains("pub enum LMessage {"), "{out}");
        assert!(out.contains("Ping { val: int },"), "{out}");
        assert!(out.contains("pub struct LPacket {"), "{out}");
        assert!(out.contains("pub x: int,"), "{out}");
        assert!(out.contains("pub node_id: int,"), "{out}");
    }

    #[test]
    fn emits_init_and_actions() {
        let out = emitted();
        assert!(out.contains("pub open spec fn LInit"), "{out}");
        assert!(out.contains("&&& s.pc is Idle"), "{out}");
        assert!(out.contains("pub open spec fn LSend("), "{out}");
        assert!(out.contains("&&& s_.pc is Done"), "{out}");
    }

    #[test]
    fn emits_the_dispatch_and_next() {
        let out = emitted();
        assert!(out.contains("LMessage::Ping { val } =>"), "{out}");
        assert!(
            out.contains("LRecv(s, s_, c, val, sent_packets)"),
            "a handler is given only what it uses -- this one never mentions the \
             sender, so it does not take `src`: {out}"
        );
        assert!(
            out.contains("exists|src: int, msg: LMessage|"),
            "LNext must quantify the received message: {out}"
        );
    }

    #[test]
    fn refuses_to_emit_an_incomplete_spec() {
        // A file missing a conjunct still looks like a spec, and would be
        // verified and reviewed as one.
        let source = r#"---- MODULE Test ----
VARIABLES x
TypeOK == x \in [Proc -> Nat]
Step(p) == x' = [x EXCEPT ![p] = CHOOSE v \in Nat : v > 0]
Next == \E p \in Proc : Step(p)
===="#;
        let module = parse_module(source).unwrap();
        let projected = project(&module).unwrap();
        assert!(
            emit(&projected).is_err(),
            "a projection with gaps must not produce source"
        );
    }
}
